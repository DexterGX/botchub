import { type NextRequest } from "next/server";
import { updateSession } from "@/lib/supabase/middleware";

export async function middleware(request: NextRequest) {
  return updateSession(request);
}

export const config = {
  matcher: [
    /*
     * Run on every request except static assets and image files — those
     * never need a refreshed auth cookie and skipping them keeps the
     * middleware cheap. Everything else (pages, API routes, Server Actions)
     * goes through so Server Components always see an up-to-date session.
     */
    "/((?!_next/static|_next/image|favicon.ico|.*\\.(?:svg|png|jpg|jpeg|gif|webp)$).*)",
  ],
};
